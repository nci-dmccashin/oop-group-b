    private void createBtnActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_createBtnActionPerformed
        // TODO add your handling code here:
        String name = nameTI.getText();
        String category = categoryTI.getText();
        // Parse text into int
        int quantity = Integer.parseInt(quantityTI.getText());
        String expiryDate = expiryDateTI.getText();
        FoodProduct newProduct = new FoodProduct(name, category, quantity, expiryDate);
        
        // Add to ArrayList
        foodItems.add(newProduct);
        
        // Display preview
        previewTA.setVisible(true);
        previewTA.setText(newProduct.printDetails());
    }//GEN-LAST:event_createBtnActionPerformed

