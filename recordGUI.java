    private void saveBtnActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_saveBtnActionPerformed
        // TODO add your handling code here:
        if (amountTf.getText().isEmpty()) {
        JOptionPane.showMessageDialog(null, "Please enter the waste amount.");
        return;
    }

        if (amountTf.getText().isEmpty()) {
        JOptionPane.showMessageDialog(null, "Please enter the waste amount.");
        return;
    }

        if (kgTf.getText().isEmpty()) {
            JOptionPane.showMessageDialog(null, "Please enter the units.");
            return;
    }

        if (productTf.getText().isEmpty()) {
            JOptionPane.showMessageDialog(null, "Please enter the product name.");
            return;
    }

        if (typeTf.getText().isEmpty()) {
            JOptionPane.showMessageDialog(null, "Please enter the waste type.");
            return;
    }

        
        units = kgTf.getText();
        item = productTf.getText();
        amount = Double.parseDouble(amountTf.getText());
        type = typeTf.getText();
         wasteRecord record = new wasteRecord();
         record.setUnits(units);
         record.setItem(item);
         record.setWasteAmount(amount);
         record.setWasteType(type);
        
         //add object to array list
         wasteList.add(record);
         //save record to file
         try{
             File outFile = new File("wasteRecord.txt");
             FileWriter fw = new FileWriter(outFile, true);
             BufferedWriter bw = new BufferedWriter(fw);
             
            bw.write(Double.toString(amount));
            bw.newLine();
            bw.write(units);
            bw.newLine();
            bw.write(type);
            bw.newLine();
            bw.write(item);
            bw.newLine();
           
             
             bw.close();
             
             JOptionPane.showMessageDialog(null, "record saved successfully");
             
            amountTf.setText("");
            kgTf.setText("");
            productTf.setText("");
            typeTf.setText("");
            
             
         } catch(IOException e){
             JOptionPane.showMessageDialog(null, "error: ");
         }
        
    //GEN-LAST:event_saveBtnActionPerformed
    }//GEN-LAST:event_saveBtnActionPerformed

    private void endBtnActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_endBtnActionPerformed
        // TODO add your handling code here:
        double plasticTotal = 0;
        double foodTotal = 0;
        double generalTotal = 0;
        double paperTotal = 0;
        double liquidTotal = 0;
        double cartonTotal = 0;
        double canTotal = 0;
        double oilTotal = 0;
        StringBuilder productDetails = new StringBuilder();
        
        try {
            File in = new File("wasteRecord.txt");
            FileReader fr = new FileReader(in);
            BufferedReader br = new BufferedReader(fr);
            
        String amountLine;
        while ((amountLine = br.readLine()) != null) {
            double amount = Double.parseDouble(amountLine);
            String units = br.readLine();
            String type = br.readLine();
            String item = br.readLine();
            productDetails.append(item)
            .append(" - ")
            .append(amount)
            .append(" ")
            .append(units)
            .append(" (")
            .append(type)
            .append(")\n");
    

        if (type.equalsIgnoreCase("plastic")) {
            plasticTotal += amount;
        }
        else if (type.equalsIgnoreCase("food")) {
            foodTotal += amount;
        }
        else if (type.equalsIgnoreCase("general")) {
            generalTotal += amount;
        }
        else if (type.equalsIgnoreCase("paper")) {
            paperTotal += amount;
        }
        else if (type.equalsIgnoreCase("liquid")) {
            liquidTotal += amount;
        }
        else if (type.equalsIgnoreCase("carton")) {
            cartonTotal += amount;
        }
        else if (type.equalsIgnoreCase("can")) {
            canTotal += amount;
        }
        else if (type.equalsIgnoreCase("oil")) {
            oilTotal += amount;
        }
    }
        br.close();
        
        JOptionPane.showMessageDialog(null,
            "WASTE REPORT\n\n"
            + "TOTAL WASTE\n"
            + "Plastic: " + plasticTotal + " kg\n"
            + "Food: " + foodTotal + " kg\n"
            + "General: " + generalTotal + " kg\n"
            + "Paper: " + paperTotal + " kg\n"
            + "Liquid: " + liquidTotal + " Lt\n"
            + "Carton: " + cartonTotal + " kg\n"
            + "Can: " + canTotal + " Lt\n"
            + "Oil: " + oilTotal + "\n\n"
            + "PRODUCTS WASTED:\n"
            + productDetails.toString()
        );
    
   } catch (IOException e){
            System.out.println(e);
  }

    }//GEN-LAST:event_endBtnActionPerformed

